// Blood II's weapon table, overridable by a mod's Mod\Weapons.txt:
//
//     [BERETTA]
//     MinDamage = 16.0
//     MaxDamage = 24.0
//
//     [SHOTGUN]
//     ShotsPerFire = 16
//
// g_WeaponDefaults (WeaponDefs.cpp) then holds the mod's value for that field of that weapon.
// Every consumer reads that array (CWeapon::Init and CViewWeapon::Create copy it into the weapon,
// the HUD and the character menu read it directly), so the table is written in place once, when
// the module loads the mod, and no consumer changes. Both modules compile their own
// WeaponDefs.cpp, so the server shell and the client shell each load the file into their own copy,
// right after LT1Mod::LoadActive; the connect check has already established they have the same
// files. A string a mod gives is never freed: CWeapon keeps the table's pointers, not copies.
//
// A section is a weapon's WEAP_ name without the prefix (SharedDefs.h), matched without case; the
// creature weapons are in the table too. A key is a field, named in BloodModWeapons.cpp's kFields;
// Blood2/ModReference/Weapons.txt lists every one with its retail value, generated by
// `testBlood2Tables --dump weapons`. m_nType is not a key: nothing reads it.
//
// HandModel, HandSkin, ProjectileClass, AltProjectileClass, StatusIcon and StatusIconH are NULL in
// retail where a weapon has none, and never ""; in those six, "" means NULL. The other ten strings
// are never NULL, and "" is "".
//
// A section naming no weapon adds one:
//
//     [DemoShotgun]
//     Base         = "SHOTGUN"
//     ShotsPerFire = 32
//
// It starts as a copy of its Base (retail's, or a new weapon above it in the file) as this mod
// leaves it, then takes its own keys. New weapons are numbered from WEAP_MAXWEAPONTYPES + 1 in file
// order, up to BLOOD2_WEAPON_IDS (127: a weapon id travels as a byte whose top bit is
// DUAL_HAND_MASK). A name is letters, digits and _, at most 31. The table only holds a new weapon;
// what makes one maps its id to its retail root through BloodModWeapon_Retail first.

#ifndef __BLOODMODWEAPONS_H__
#define __BLOODMODWEAPONS_H__

#include <string>

namespace LT1Mod { class FileSource; }

// The section name of weapon id nId (1 .. BloodModWeapon_Count()), or NULL
const char* BloodModWeapon_Name(int nId);
// An id by section name, without case, or 0
int BloodModWeapon_Find(const char* pName);

// The highest id in use: WEAP_MAXWEAPONTYPES, plus the mod's new weapons
int BloodModWeapon_Count();
// A new weapon's Base (an id), or 0; and the retail weapon at the end of its chain of Bases, or
// any other id itself, so BloodModWeapon_Retail(id) can stand wherever retail code tests an id
int BloodModWeapon_Base(int nId);
int BloodModWeapon_Retail(int nId);

// The keys, in table order; NULL past the last
const char* BloodModWeapon_Key(int nField);
// Weapon nId's value for one key, as Weapons.txt writes it ("16.0", "<0.6, -0.6, 1.9>",
// "\"Sounds\\...\"", "TRUE", "PISTOL"): the current table's, or retail's
std::string BloodModWeapon_Value(int nId, int nField, bool bRetail = false);

// Loads Mod\Weapons.txt through src into g_WeaponDefaults, after setting the table back to
// retail. An absent file is no overrides and no error. A file with any error loads nothing and
// returns false with sError saying where. With no active mod this restores retail and returns
// true.
bool BloodModWeapons_Load(LT1Mod::FileSource &src, std::string &sError);

// Sets g_WeaponDefaults back to retail
void BloodModWeapons_Clear();

// One line per weapon whose values differ from retail, "BERETTA: MinDamage 16.0, MaxDamage
// 24.0", in id order: what a shell prints after loading
std::string BloodModWeapons_Summary();

// Every weapon's every retail value, as a Weapons.txt: the reference file
std::string BloodModWeapons_Reference();

// Loads, and prints the summary or the error to the console a line at a time, each line after
// pPrefix ("Server: " on the server). What both shells call.
void BloodModWeapons_LoadAndReport(LT1Mod::FileSource &src, void (*pPrint)(const char *pLine), const char *pPrefix);

#endif // __BLOODMODWEAPONS_H__
