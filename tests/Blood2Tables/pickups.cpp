#include "harness.h"

#include <stdio.h>
#include <string.h>
#include <string>

namespace
{

bool LoadPickups(const std::string& text, std::string& err)
{
	return MountAndLoad("Mod\\Pickups.txt", text, err, BloodModPickups_Load);
}

void Unload()
{
	BloodModPickups_Clear();
	LT1Mod::SetActive(LT1Mod::State());
}

struct Retail { int nRow; int nItem; const char* pModel; const char* pName; int nNameId; };
const Retail kRetail[] =
{
	{ BMPU_BINOCULARS, INV_BINOCULARS, "Binoculars_pu", "Binoculars", IDS_ITEM_BINOCULARS },
	{ BMPU_THEEYE, INV_THEEYE, "TheEye_pu", "The Eye", IDS_ITEM_EYE },
	{ BMPU_FLASHLIGHT, INV_FLASHLIGHT, "Flashlight_pu", "Flashlight", IDS_ITEM_FLASHLIGHT },
	{ BMPU_MEDKIT, INV_MEDKIT, "Medkit_pu", "Medkit", IDS_ITEM_MEDKIT },
	{ BMPU_NIGHTGOGGLES, INV_NIGHTGOGGLES, "NightGoggles_pu", "Night Goggles", IDS_ITEM_GOGGLES },
	{ BMPU_PROXIMITIES, INV_PROXIMITY, "Proximities_pu", "Proximity Bomb", IDS_ITEM_PROX },
	{ BMPU_REMOTES, INV_REMOTE, "Remotes_pu", "Remote Bomb", IDS_ITEM_REMOTE },
	{ BMPU_TIMEBOMB, INV_TIMEBOMB, "TimeBomb_pu", "Time Bomb", IDS_ITEM_TIME },
};

int RetailRows(int nSkip = -1)
{
	int n = 0;
	for (size_t i = 0; i < sizeof(kRetail) / sizeof(kRetail[0]); ++i)
	{
		if (kRetail[i].nRow == nSkip) continue;
		const BloodModItemPickup& p = BloodModPickup_Row(kRetail[i].nRow);
		n += p.nItem == kRetail[i].nItem && !strcmp(p.szModel, kRetail[i].pModel) && !strcmp(p.szName, kRetail[i].pName) &&
			 BloodModPickup_NameId(p.nName) == kRetail[i].nNameId;
	}
	return n;
}

} // namespace

std::string PickupsDump()
{
	return
		"// Blood II's item pickups, as Mod\\Pickups.txt sets them.  GENERATED by\n"
		"// `testBlood2Tables --dump pickups` from Blood2/ObjectDLL/BloodModPickups.cpp,\n"
		"// which transcribes ItemPickups.cpp's constructors; do not edit,\n"
		"// regenerate.\n"
		"//\n"
		"// A section is a pickup class a level places.  Item is an INV_ name, Model\n"
		"// the pickup's model (Models\\Powerups\\<Model>.abc), Name what it says,\n"
		"// NameID its IDS_ string.  A mod names only what it changes:\n"
		"//\n"
		"//     [TheEyePU]\n"
		"//     Item = \"MEDKIT\"\n"
		"//\n"
		"// Blood2/ObjectDLL/BloodModPickups.h has the rest.\n"
		+ BloodModPickups_Reference();
}

void PickupsSelfTest()
{
	printf("pickups: retail\n");
	Unload();
	Check(RetailRows() == BMPU_COUNT && !strcmp(BloodModPickup_Name(BMPU_THEEYE), "TheEyePU"),
		  "with no mod each of the eight classes gives its constructor's item, model, name and string");

	printf("pickups: mod\n");
	std::string err;
	const bool bLoaded = LoadPickups("[TheEyePU]\nItem = \"MEDKIT\"\nModel = \"Medkit_pu\"\nName = \"Medkit\"\n"
									 "NameID = \"ITEM_MEDKIT\"\n", err);
	const BloodModItemPickup& p = BloodModPickup_Row(BMPU_THEEYE);
	Check(bLoaded && p.nItem == INV_MEDKIT && !strcmp(p.szModel, "Medkit_pu") && !strcmp(p.szName, "Medkit") &&
		  BloodModPickup_NameId(p.nName) == IDS_ITEM_MEDKIT && RetailRows(BMPU_THEEYE) == BMPU_COUNT - 1,
		  "a row moves to the mod's values, its NameID the string's id, and no other row moves: " + err);
	Unload();
	Check(RetailRows() == BMPU_COUNT, "and unloading puts it back");

	printf("pickups: round trip\n");
	Check(LoadPickups(PickupsDump(), err) && RetailRows() == BMPU_COUNT && BloodModPickups_Summary().empty(),
		  "the dump loads as a mod and changes nothing: " + err);
	Unload();

	printf("pickups: errors\n");
	struct Bad { const char* label; const char* text; const char* expect; };
	const Bad bad[] =
	{
		{ "a class there is not",		"[JetpackPU]\nName = \"Jetpack\"\n",	"JetpackPU" },
		{ "a bomb from an item's class",	"[TheEyePU]\nItem = \"TIMEBOMB\"\n",	"[TheEyePU]:Item: a charged item's pickup gives one" },
		{ "an item from a bomb's class",	"[RemotesPU]\nItem = \"MEDKIT\"\n",		"[RemotesPU]:Item: a bomb's pickup gives a bomb" },
	};
	for (size_t i = 0; i < sizeof(bad) / sizeof(bad[0]); ++i)
	{
		err.clear();
		Check(!LoadPickups(bad[i].text, err) && err.find(bad[i].expect) != std::string::npos && RetailRows() == BMPU_COUNT,
			  std::string(bad[i].label) + " loads nothing: " + err);
	}
	Unload();
}
