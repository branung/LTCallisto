// pickups.cpp: testBlood2Tables for Mod\Pickups.txt (BloodModPickups.h).
//
//   retail      with no mod each class gives what ItemPickups.cpp's
//               constructor gave.
//   mod         a row moves and no other, and its NameID is the string's id.
//   round trip  the --dump file loads as a mod and changes nothing.
//   errors      a class there is not, a bomb from a charged item's class,
//               a charged item from a bomb's.

