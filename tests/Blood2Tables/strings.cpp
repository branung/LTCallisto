// testBlood2Tables for Mod\Strings.txt (Shared/BloodModStrings.h).
// The parser is libs/LT1Mod/lt1mod_strings.h's and is checked in full by tests/ShogoTables.
// These checks cover Blood 2's half:
//   names   the generated list is every IDS_ name Shared/ClientRes.h defines, matched without case
//   errors  a name Blood 2 does not have is refused and loads nothing
//   module  retail's strings come from the built string module (CRes), calibrated by two known strings;
//           then a round trip (the reference as a mod answers every id as retail) and one override per string

