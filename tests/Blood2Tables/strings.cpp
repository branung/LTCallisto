std::string g_CResPath;

namespace
{

bool ReadCRes(std::map<int, std::string>& out)
{
	out.clear();
#ifdef _WIN32
	HMODULE h = LoadLibraryExA(g_CResPath.c_str(), NULL, LOAD_LIBRARY_AS_DATAFILE);
	if (!h) return false;
	static char buf[5000];
	for (int id = 0; id <= 65535; ++id)
		if (LoadStringA(h, (UINT)id, buf, sizeof(buf)) > 0) out[id] = buf;
	FreeLibrary(h);
	return true;
#else
	void* h = dlopen(g_CResPath.c_str(), RTLD_NOW | RTLD_LOCAL);
	if (!h) return false;
	typedef const char* (*LoadStringFn)(uint32_t);
	LoadStringFn pLoad = (LoadStringFn)dlsym(h, "LoadString");
	if (!pLoad) { dlclose(h); return false; }
	for (int id = 0; id <= 65535; ++id)
	{
		const char* p = pLoad((uint32_t)id);
		if (p) out[id] = p;
	}
	dlclose(h);
	return true;
#endif
}

bool LoadStrings(const std::string& text, std::string& err)
{
	return MountAndLoad("Mod\\Strings.txt", text, err, BloodModStrings_Load);
}

void Unload()
{
	BloodModStrings_Clear();
	LT1Mod::SetActive(LT1Mod::State());
}

std::string StrKey(int id)
{
	const char* p = BloodModString_Name(id);
	return p ? std::string(p) : std::to_string(id);
}

int CountHeaderNames()
{
	std::ifstream f(BLOOD2_CLIENTRES_H);
	std::string line;
	std::set<std::string> names;
	while (std::getline(f, line))
	{
		char name[256];
		int n;
		if (sscanf(line.c_str(), " #define %255s %d", name, &n) == 2 && strncmp(name, "IDS_", 4) == 0) names.insert(name);
	}
	return (int)names.size();
}

} // namespace

std::string StringsDump(const std::map<int, std::string>& retail)
{
	std::ostringstream o;
	o << "// Blood II's text strings, every one retail's string module (CRes) holds:\n"
		 "// the reference for a mod's Mod\\Strings.txt. GENERATED by\n"
		 "// `testBlood2Tables --dump strings` from the built string module; do not\n"
		 "// edit, regenerate. testBlood2Tables proves that loading this file as a\n"
		 "// mod changes nothing.\n"
		 "//\n"
		 "// One `key = \"text\"` per line: the key is an IDS_ name from\n"
		 "// Shared/ClientRes.h, or the id where the string has no name; the text\n"
		 "// takes \\n \\r \\t \\\" \\\\.  %1!s! and the like are the game's inserts:\n"
		 "// keep the ones a string has, or the game reads an argument it never\n"
		 "// passed. A mod copies only the lines it changes. Blood2/Shared/\n"
		 "// BloodModStrings.h has the rest.\n"
		 "\n";
	for (std::map<int, std::string>::const_iterator it = retail.begin(); it != retail.end(); ++it)
		o << StrKey(it->first) << " = " << BloodModString_Quote(it->second.c_str()) << "\n";
	return o.str();
}

bool StringsRetail(std::map<int, std::string>& out)
{
	return ReadCRes(out);
}

void StringsSelfTest()
{
	printf("strings\n");
	Unload();
	std::string err;

	Check(BloodModString_NameCount() == CountHeaderNames() &&
		  BloodModString_Id("IDS_MENU_MAIN_SINGLEPLAYER") == IDS_MENU_MAIN_SINGLEPLAYER &&
		  BloodModString_Id("ids_menu_main_singleplayer") == IDS_MENU_MAIN_SINGLEPLAYER &&
		  BloodModString_Id("IDS_GUNPICKUP") == -1,
		  "strings: " + std::to_string(BloodModString_NameCount()) + " IDS_ names, every one Shared/ClientRes.h defines, "
		  "matched without case (and Shogo's IDS_GUNPICKUP is not one)");

	LoadStrings("IDS_MENU_MAIN_SINGLEPLAYER = \"Begin\"\n", err);
	const bool bBefore = BloodModString(IDS_MENU_MAIN_SINGLEPLAYER) != 0;
	const bool bLoaded = LoadStrings("IDS_GUNPICKUP = \"x\"\n", err);
	Check(bBefore && !bLoaded && !BloodModStrings_Active() && err.find("is not one of Blood 2's IDS_ names") != std::string::npos &&
		  err.find("Blood2/ModReference/Strings.txt") != std::string::npos && err.find("line 1") != std::string::npos,
		  "strings: a name Blood 2 does not have loads nothing, over a mod loaded before it: " + err);
	Unload();

	LoadStrings("IDS_MENU_MAIN_SINGLEPLAYER = \"Begin\"\nIDS_MENU_MAIN_QUIT = \"Leave\"\n", err);
	Check(BloodModString_ProbeId() == IDS_MENU_MAIN_SINGLEPLAYER &&
		  BloodModStrings_Summary() == "2 strings: IDS_MENU_MAIN_SINGLEPLAYER, IDS_MENU_MAIN_QUIT",
		  "strings: the probe and the summary (" + BloodModStrings_Summary() + ")" + (err.empty() ? "" : ": " + err));
	Unload();

	std::map<int, std::string> retail;
	if (!ReadCRes(retail))
	{
		printf("  skip  strings: no string module at %s, so the round trip and the mutation test did not run\n",
			   g_CResPath.c_str());
		return;
	}
	// Known answers from ClientRes.rc: a plain string and one with \n and "" escapes
	Check(retail.size() > 700 && retail[IDS_MENU_MAIN_SINGLEPLAYER] == "SINGLE PLAYER" &&
		  retail[IDS_HELP_NIGHTCOLOR] == "Specifies the color of the night sky in RGB format.\n\nDefault value is \"0.5 0.5 0.5\".",
		  "strings calibration: the module holds " + std::to_string(retail.size()) + " strings, two read as ClientRes.rc spells them "
		  "(its \\n and \"\" escapes included)");

	const std::string dump = StringsDump(retail);
	Check(LoadStrings(dump, err), "strings: the dump loads as a mod" + (err.empty() ? std::string() : ": " + err));
	int nBad = 0;
	std::string first;
	for (int id = 0; id <= 65535; ++id)
	{
		const char* p = BloodModString(id);
		std::map<int, std::string>::const_iterator it = retail.find(id);
		const bool bSame = it == retail.end() ? p == 0 : (p && it->second == p);
		if (!bSame) { if (!nBad) first = StrKey(id); ++nBad; }
	}
	Check(nBad == 0, nBad ? "strings: round trip differs on " + std::to_string(nBad) + " ids, first " + first
						  : "strings: every one of the " + std::to_string(retail.size()) + " strings, and no other id, "
							"answers with retail's text with the dump loaded");
	Unload();

	int nCases = 0;
	nBad = 0;
	for (std::map<int, std::string>::const_iterator it = retail.begin(); it != retail.end(); ++it)
	{
		std::string why;
		if (!LoadStrings(StrKey(it->first) + " = \"modtest\"\n", err)) why = "did not load: " + err;
		else
		{
			const char* p = BloodModString(it->first);
			if (!p || strcmp(p, "modtest") != 0) why = "the id does not answer";
			for (std::map<int, std::string>::const_iterator o = retail.begin(); o != retail.end() && why.empty(); ++o)
				if (o->first != it->first && BloodModString(o->first)) why = "changed " + StrKey(o->first);
		}
		++nCases;
		if (!why.empty()) { if (!nBad) first = StrKey(it->first) + " " + why; ++nBad; }
		Unload();
	}
	Check(nBad == 0, nBad ? "strings mutation: " + std::to_string(nBad) + " of " + std::to_string(nCases) + " fail, first " + first
						  : "strings: " + std::to_string(nCases) + " single-field overrides each change their own string and nothing else");

	// The example mod in tests/Blood2Tables/strings_mod
	const std::string text = Slurp(BLOOD2_STRINGS_MOD);
	const bool bMod = LoadStrings(text, err);
	Check(bMod && BloodModStrings_Summary() == "2 strings: IDS_MENU_MAIN_SINGLEPLAYER, IDS_MENU_MAIN_QUIT" &&
		  BloodModString_ProbeId() == IDS_MENU_MAIN_SINGLEPLAYER,
		  "strings: the example mod loads, and its summary is: " + BloodModStrings_Summary() + (err.empty() ? "" : " " + err));
	Unload();
}
