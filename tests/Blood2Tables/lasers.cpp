// lasers.cpp: testBlood2Tables for Mod\Lasers.txt (BloodModLasers.h).
//
//   names       the fourteen LASER_ ids, by SFXMsgIds.h's numbers.
//   retail      with no mod a small and a large beam are SetupBeam's two
//               shapes, each color its skin.
//   mod         a key moves its laser and no other, and unloading puts it back.
//   round trip  the --dump file loads as a mod and changes nothing.
//   errors      a laser there is not, a key there is not.

#include "server_de.h"
#include "SFXMsgIds.h"
#include "BloodModLasers.h"
#include "harness.h"

#include <stdio.h>
#include <string.h>
#include <string>

namespace
{

bool LoadLasers(const std::string& text, std::string& err)
{
	return MountAndLoad("Mod\\Lasers.txt", text, err, BloodModLasers_Load);
}

void Unload()
{
	BloodModLasers_Clear();
	LT1Mod::SetActive(LT1Mod::State());
}

bool IsRetail(int nType)
{
	const LaserRecipe* p = BloodModLaser_Get(nType);
	const bool bLarge = (nType % 2) == 1;
	static const char* const kSkins[] = { "beamred", "beamgreen", "beamblue", "beamwhite", "beamyellow", "beamorange", "beampurple" };
	const std::string skin = std::string("Skins\\Ammo\\") + kSkins[nType / 2] + ".dtx";
	return p && p->fMinScale == (bLarge ? 0.1f : 0.05f) && p->fMaxScale == (bLarge ? 2.5f : 1.0f) &&
		   p->fDuration == (bLarge ? 1.0f : 0.5f) && p->fScaleTime == (bLarge ? 0.35f : 0.25f) &&
		   p->fFadeTime == (bLarge ? 0.35f : 0.25f) && p->fAlpha == 0.5f && !p->bWaveForm &&
		   !strcmp(p->szModel, "Models\\Ammo\\beam.abc") && skin == p->szSkin;
}

} // namespace

std::string LasersDump()
{
	return
		"// Blood II's laser beams, as Mod\\Lasers.txt sets them.  GENERATED by\n"
		"// `testBlood2Tables --dump lasers` from Blood2/Shared/BloodModLasers.cpp,\n"
		"// which transcribes ClientShellDLL/LaserBeamFX.cpp's SetupBeam; do not\n"
		"// edit, regenerate.\n"
		"//\n"
		"// A section is a LASER_ name without the prefix.  A beam grows from\n"
		"// MinScale to MaxScale over ScaleTime, fades over FadeTime and is gone\n"
		"// after Duration.  A mod names only what it changes:\n"
		"//\n"
		"//     [YELLOW_SMALL]\n"
		"//     Duration = 0.015625\n"
		"//\n"
		"// Blood2/Shared/BloodModLasers.h has the rest.\n"
		+ BloodModLasers_Reference();
}

void LasersSelfTest()
{
	printf("lasers: names\n");
	Unload();
	Check(BloodModLaser_Find("yellow_small") == LASER_YELLOW_SMALL && BloodModLaser_Find("PURPLE_LARGE") == LASER_PURPLE_LARGE &&
		  BloodModLaser_Find("RED_SMALL") == LASER_RED_SMALL && BloodModLaser_Find("PINK_SMALL") < 0 &&
		  !strcmp(BloodModLaser_Name(LASER_ORANGE_SMALL), "ORANGE_SMALL") && !BloodModLaser_Get(BLOODMOD_LASER_COUNT) &&
		  !BloodModLaser_Get(-1),
		  "the fourteen LASER_ names are SFXMsgIds.h's numbers, matched without case; past them, none");

	printf("lasers: retail\n");
	int nRetail = 0;
	for (int t = 0; t < BLOODMOD_LASER_COUNT; ++t) nRetail += IsRetail(t);
	Check(nRetail == BLOODMOD_LASER_COUNT, "with no mod each laser is SetupBeam's: a small or a large shape and its colour's skin");

	printf("lasers: mod\n");
	std::string err;
	const bool bLoaded = LoadLasers("[YELLOW_SMALL]\nMinScale = 0.2\nDuration = 0.015625\nAlpha = 256.0\n", err);
	const LaserRecipe* p = BloodModLaser_Get(LASER_YELLOW_SMALL);
	int nOthers = 0;
	for (int t = 0; t < BLOODMOD_LASER_COUNT; ++t) if (t != LASER_YELLOW_SMALL) nOthers += IsRetail(t);
	Check(bLoaded && p->fMinScale == 0.2f && p->fDuration == 0.015625f && p->fAlpha == 256.0f && p->fMaxScale == 1.0f &&
		  nOthers == BLOODMOD_LASER_COUNT - 1,
		  "a key moves its laser and no other: " + err);
	Check(BloodModLasers_Summary() == "YELLOW_SMALL: MinScale 0.2, Duration 0.015625, Alpha 256.0",
		  "the summary names what moved: " + BloodModLasers_Summary());
	Unload();
	Check(IsRetail(LASER_YELLOW_SMALL), "and unloading puts it back");

	printf("lasers: round trip\n");
	const bool bTrip = LoadLasers(LasersDump(), err);
	int nSame = 0;
	for (int t = 0; t < BLOODMOD_LASER_COUNT; ++t) nSame += IsRetail(t);
	Check(bTrip && nSame == BLOODMOD_LASER_COUNT && BloodModLasers_Summary().empty(),
		  "the dump loads as a mod and changes nothing: " + err);
	Unload();

	printf("lasers: errors\n");
	err.clear();
	Check(!LoadLasers("[PINK_SMALL]\nAlpha = 1.0\n", err) && err.find("PINK_SMALL") != std::string::npos,
		  "a laser there is not loads nothing: " + err);
	err.clear();
	Check(!LoadLasers("[RED_SMALL]\nColour = 1.0\n", err) && err.find("Colour") != std::string::npos && IsRetail(LASER_RED_SMALL),
		  "a key there is not loads nothing: " + err);
	Unload();
}
