// objectfx.cpp: testBlood2Tables for Mod\ObjectFX.txt (BloodModObjectFX.h). Retail's recipes
// are code, so the table holds only a mod's; the checks are the loader's:
//
//   names       a section is an OBJFX_ name, with or without a level suffix,
//               and a level suffix scopes it to that level alone.
//   fields      each key, set alone, sets its one field to its value.
//   words       emit types and flag words by name, written back the same.
//   round trip  every field's text, read again, is the same recipe.
//   errors      a bad file loads nothing, over a mod loaded before it.

#include "server_de.h"
#include "SFXMsgIds.h"
#include "BloodModObjectFX.h"
#include "harness.h"

#include <stdio.h>
#include <string.h>
#include <string>

namespace
{

bool LoadOFX(const std::string& text, std::string& err)
{
	return MountAndLoad("Mod\\ObjectFX.txt", text, err, BloodModObjectFX_Load);
}

void Unload()
{
	BloodModObjectFX_Clear();
	LT1Mod::SetActive(LT1Mod::State());
}

int CountSet(const BloodModObjFXRecipe* r)
{
	int n = 0;
	for (int f = 0; r && f < BMO_FIELDS; ++f) n += r->bSet[f] ? 1 : 0;
	return n;
}

// A value for field f that no zeroed recipe holds, as the file writes it.
const char* Sample(int f)
{
	switch (f)
	{
		case BMO_OFFSET: case BMO_ROTATIONS: case BMO_MINCOLOR: case BMO_MAXCOLOR:	return "<20, -1.5, 0.25>";
		case BMO_GRAVITY: case BMO_MINVELOCITY: case BMO_MAXVELOCITY:				return "-150.0";
		case BMO_NUMPARTICLES:														return "72";
		case BMO_EMITTYPE:															return "\"FILLEDSPHERE\"";
		case BMO_RAMPUPTYPE: case BMO_RAMPDOWNTYPE:									return "\"ALPHA | POSRADIUS\"";
		case BMO_FXFLAGS:															return "\"MOVINGSOURCE | MOVINGSTREAM\"";
		case BMO_PARTICLE:															return "\"SpriteTextures\\flames1_09.dtx\"";
	}
	return "0.4";
}

} // namespace

std::string ObjectFXDump()
{
	return
		"// Blood II's object effects, which Mod\\ObjectFX.txt changes.  GENERATED by\n"
		"// `testBlood2Tables --dump objectfx` from Blood2/Shared/BloodModObjectFX.cpp;\n"
		"// do not edit, regenerate.\n"
		"//\n"
		"// An object effect is one particle system the client fills in code per\n"
		"// detail level (ClientShellDLL/ObjectFX.cpp, CObjectGeneralFX::CreateObject).\n"
		"// A section names an effect, with _HIGH, _MEDIUM or _LOW for one level:\n"
		"//\n"
		"//     [FLAMING_2_HIGH]\n"
		"//     Particle = \"SpriteTextures\\flames1_09.dtx\"\n"
		"//\n"
		"// Blood2/Shared/BloodModObjectFX.h has the rest.\n"
		+ BloodModObjectFX_Reference();
}

void ObjectFXSelfTest()
{
	std::string err;
	printf("objectfx: names\n");
	Unload();
	Check(!BloodModObjectFX_Recipe(OBJFX_SMOKING_1, 2) && BloodModObjectFX_Summary().empty(),
		  "with no mod no effect has a recipe");
	bool bOk = LoadOFX("[smoking_1]\nAlpha = 0.05\n\n[FLAMING_2_high]\nDensity = 2\n", err);
	const BloodModObjFXRecipe* a0 = BloodModObjectFX_Recipe(OBJFX_SMOKING_1, 0);
	const BloodModObjFXRecipe* a2 = BloodModObjectFX_Recipe(OBJFX_SMOKING_1, 2);
	const BloodModObjFXRecipe* f2 = BloodModObjectFX_Recipe(OBJFX_FLAMING_2, 2);
	Check(bOk && a0 && a2 && BloodModObjectFX_Recipe(OBJFX_SMOKING_1, 1) && a0->lo[BMO_ALPHA][0] == 0.05f &&
		  f2 && f2->lo[BMO_DENSITY][0] == 2.0f && !BloodModObjectFX_Recipe(OBJFX_FLAMING_2, 1) &&
		  !BloodModObjectFX_Recipe(OBJFX_FLAMING_2, 0) && !BloodModObjectFX_Recipe(OBJFX_FLAMING_1, 2),
		  "a section with no level is all three, one with a level that level alone, names without case");
	Check(BloodModObjectFX_Summary() ==
		  "SMOKING_1_LOW: Alpha 0.05\nSMOKING_1_MEDIUM: Alpha 0.05\nSMOKING_1_HIGH: Alpha 0.05\nFLAMING_2_HIGH: Density 2.0",
		  ("the summary names each level: " + BloodModObjectFX_Summary()).c_str());

	printf("objectfx: fields\n");
	int nBad = 0;
	for (int f = 0; f < BMO_FIELDS; ++f)
	{
		const std::string key = BloodModObjectFX_FieldName(f);
		if (!LoadOFX("[SPARKS_2_MEDIUM]\n" + key + " = " + Sample(f) + "\n", err)) { ++nBad; printf("        %s: %s\n", key.c_str(), err.c_str()); continue; }
		const BloodModObjFXRecipe* r = BloodModObjectFX_Recipe(OBJFX_SPARKS_2, 1);
		const std::string back = r ? BloodModObjectFX_Value(*r, f) : std::string();
		// The value written back, reloaded, is the same recipe.
		std::string again = "[SPARKS_2_MEDIUM]\n" + key + " = " + back + "\n";
		BloodModObjFXRecipe first = r ? *r : BloodModObjFXRecipe();
		const bool bOne = r && CountSet(r) == 1 && r->bSet[f] && !r->bReplace;
		const bool bAgain = LoadOFX(again, err);
		const BloodModObjFXRecipe* s = BloodModObjectFX_Recipe(OBJFX_SPARKS_2, 1);
		const bool bSame = s && bAgain && !memcmp(first.lo[f], s->lo[f], sizeof(first.lo[f])) && !memcmp(first.hi[f], s->hi[f], sizeof(first.hi[f])) && first.n[f] == s->n[f] &&
						   first.sParticle == s->sParticle;
		if (!bOne || !bSame) { ++nBad; printf("        %s = %s -> %s\n", key.c_str(), Sample(f), back.c_str()); }
	}
	char b[160];
	snprintf(b, sizeof(b), "each of the %d keys sets its own field alone, and its text reads back the same", (int)BMO_FIELDS);
	Check(nBad == 0 && BMO_FIELDS == 23, b);

	printf("objectfx: words\n");
	bOk = LoadOFX("[ORBTRAIL_1_LOW]\nFXFlags = \"ALL\"\nEmitType = \"cylinder\"\nRampDownType = \"\"\nRampUpType = \"NumParticles\"\n"
				  "\n[ORBTRAIL_2_LOW]\nFXFlags = \"STREAMING | ROTATINGSOURCE\"\nReplace = TRUE\nParticle = \"\"\n", err);
	const BloodModObjFXRecipe* o1 = BloodModObjectFX_Recipe(OBJFX_ORBTRAIL_1, 0);
	const BloodModObjFXRecipe* o2 = BloodModObjectFX_Recipe(OBJFX_ORBTRAIL_2, 0);
	Check(bOk && o1 && o1->n[BMO_FXFLAGS] == 0xFF && o1->n[BMO_EMITTYPE] == 3 && o1->n[BMO_RAMPDOWNTYPE] == 0 &&
		  o1->bSet[BMO_RAMPDOWNTYPE] && o1->n[BMO_RAMPUPTYPE] == 0x04 &&
		  BloodModObjectFX_Value(*o1, BMO_FXFLAGS) == "\"ALL\"" && BloodModObjectFX_Value(*o1, BMO_EMITTYPE) == "\"CYLINDER\"" &&
		  o2 && o2->bReplace && o2->n[BMO_FXFLAGS] == 0x1C && o2->bSet[BMO_PARTICLE] && o2->sParticle.empty() &&
		  BloodModObjectFX_Value(*o2, BMO_FXFLAGS) == "\"MOVINGSOURCE | MOVINGSTREAM | ROTATINGSOURCE\"",
		  "names any case, composites as their bits, \"\" for no flags or no particle, and Replace");

	printf("objectfx: ranges\n");
	bOk = LoadOFX("[SINGULARITY_1_HIGH]\nPosRadius = \"75..100\"\nRotations = \"<0..0.01, 0..0.015, -0.5>\"\nGravity = -3\n", err);
	const BloodModObjFXRecipe* g = BloodModObjectFX_Recipe(OBJFX_SINGULARITY_1, 2);
	Check(bOk && g && g->lo[BMO_POSRADIUS][0] == 75.0f && g->hi[BMO_POSRADIUS][0] == 100.0f &&
		  g->lo[BMO_ROTATIONS][1] == 0.0f && g->hi[BMO_ROTATIONS][1] == 0.015f && g->lo[BMO_ROTATIONS][2] == -0.5f &&
		  g->hi[BMO_ROTATIONS][2] == -0.5f && g->lo[BMO_GRAVITY][0] == -3.0f && g->hi[BMO_GRAVITY][0] == -3.0f &&
		  BloodModObjectFX_Value(*g, BMO_POSRADIUS) == "\"75.0..100.0\"" &&
		  BloodModObjectFX_Value(*g, BMO_ROTATIONS) == "\"<0.0..0.01, 0.0..0.015, -0.5>\"" &&
		  BloodModObjectFX_Value(*g, BMO_GRAVITY) == "-3.0",
		  ("a number or a vector's part may be a range, quoted, as retail's GetRandom ones: " +
		   (g ? BloodModObjectFX_Value(*g, BMO_ROTATIONS) : err)).c_str());

	printf("objectfx: errors\n");
	struct Bad { const char* pWhat; const char* pText; const char* pWant; };
	const std::string sLong = "[SMOKING_1]\nParticle = \"" + std::string(100, 'x') + "\"\n";
	const Bad kBad[] =
	{
		{ "an effect there is not",		"[SMOKING_9]\nAlpha = 1\n",							"is not a Blood 2 object effect" },
		{ "a prefix kept",				"[OBJFX_SMOKING_1]\nAlpha = 1\n",					"is not a Blood 2 object effect" },
		{ "all levels and one",			"[SMOKING_1]\nAlpha = 1\n\n[SMOKING_1_LOW]\nAlpha = 2\n", "is given twice" },
		{ "a key there is not",			"[SMOKING_1]\nColour = <1,1,1>\n",					"has no key \"Colour\"" },
		{ "an emit type there is not",	"[SMOKING_1]\nEmitType = \"CONE\"\n",				"is not an emit type" },
		{ "a flag there is not",		"[SMOKING_1]\nFXFlags = \"ALL | SPIN\"\n",			"names a flag there is not" },
		{ "a ramp flag as a flag",		"[SMOKING_1]\nRampUpType = \"STREAMING\"\n",		"names a flag there is not" },
		{ "a negative density",			"[SMOKING_1]\nDensity = -1\n",						"is below 0" },
		{ "a negative count",			"[SMOKING_1]\nNumParticles = -2\n",					"is below 0" },
		{ "a number as a vector",		"[SMOKING_1]\nOffset = 3\n",						"" },
		{ "half a range",				"[SMOKING_1]\nRadius = \"75..\"\n",				"not a number or a range" },
		{ "a range below 0",			"[SMOKING_1]\nRadius = \"-5..5\"\n",				"is below 0" },
		{ "a vector of two",			"[SMOKING_1]\nOffset = \"<1..2, 3>\"\n",			"not a vector" },
		{ "a particle too long",		sLong.c_str(), "longer than 99" },
	};
	int nErr = 0;
	for (size_t i = 0; i < sizeof(kBad) / sizeof(kBad[0]); ++i)
	{
		LoadOFX("[HEAL_1]\nAlpha = 0.5\n", err);
		const bool bLoaded = LoadOFX(kBad[i].pText, err);
		const bool bGood = !bLoaded && err.find(kBad[i].pWant) != std::string::npos && !BloodModObjectFX_Recipe(OBJFX_HEAL_1, 0) &&
						   !BloodModObjectFX_Recipe(OBJFX_SMOKING_1, 0);
		if (!bGood) { ++nErr; printf("        %s: %s\n", kBad[i].pWhat, err.c_str()); }
	}
	snprintf(b, sizeof(b), "%d bad files each load nothing, over a mod loaded before, and say why", (int)(sizeof(kBad) / sizeof(kBad[0])));
	Check(nErr == 0, b);
	Unload();
}
