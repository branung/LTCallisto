#!/usr/bin/env python3
"""A game's string-id names for a mod's Mod\\Strings.txt.

Writes Shogo/Shared/ShogoModStringIds.inc from the IDS_ defines in Shogo/Shared/ClientRes.h, or,
with --game blood2, Blood2/Shared/BloodModStringIds.inc from Blood II's: one SMS_STRING_ID(IDS_NAME)
line per name, in the header's order. The .inc carries names only; the numbers come from compiling
it against ClientRes.h itself, so a name and its id cannot disagree, and a name removed from the
header fails the build. This tool guards the other direction, a name added to the header and
missing here:

    python3 tools/shogo_string_ids.py [--game blood2] --write
    python3 tools/shogo_string_ids.py [--game blood2] --check     # exit 1 if the .inc is stale
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAMES = {
    'shogo': ('Shogo', 'ShogoModStringIds.inc', 'ShogoModStrings.cpp'),
    'blood2': ('Blood2', 'BloodModStringIds.inc', 'BloodModStrings.cpp'),
}
HEADER = OUT = USER = None


def select(game):
    global HEADER, OUT, USER
    folder, inc, user = GAMES[game]
    HEADER = os.path.join(ROOT, folder, 'Shared', 'ClientRes.h')
    OUT = os.path.join(ROOT, folder, 'Shared', inc)
    USER = user


def render():
    names = []
    with open(HEADER, encoding='latin-1') as f:
        for line in f:
            m = re.match(r'\s*#define\s+(IDS_\w+)\s+\d+\s*$', line)
            if m and m.group(1) not in names:
                names.append(m.group(1))
    lines = ['// GENERATED by tools/shogo_string_ids.py from Shared/ClientRes.h: do not',
             '// edit; rerun it with --write. Every IDS_ name, for Mod\\Strings.txt',
             '// (%s defines SMS_STRING_ID before including this).' % USER,
             '// %d names.' % len(names)]
    lines += ['SMS_STRING_ID(%s)' % n for n in names]
    return '\n'.join(lines) + '\n'


def main(argv):
    argv = list(argv)
    game = 'shogo'
    if len(argv) >= 3 and argv[1] == '--game':
        game = argv[2]
        del argv[1:3]
    if game not in GAMES:
        sys.stderr.write('unknown game %s (%s)\n' % (game, ', '.join(sorted(GAMES))))
        return 2
    select(game)
    text = render()
    if argv[1:] == ['--write']:
        with open(OUT, 'w', newline='\n') as f:
            f.write(text)
        return 0
    if argv[1:] == ['--check']:
        try:
            # Carriage returns ignored: a Windows checkout holds the committed LF file as CRLF
            with open(OUT, newline='') as f:
                current = f.read().replace('\r\n', '\n')
        except OSError:
            current = None
        if current == text:
            print('%s is current' % os.path.relpath(OUT, ROOT))
            return 0
        print('%s is STALE: run tools/shogo_string_ids.py%s --write' %
              (os.path.relpath(OUT, ROOT), '' if game == 'shogo' else ' --game ' + game))
        return 1
    sys.stderr.write(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv))
